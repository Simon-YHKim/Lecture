def main():
    dry = "--dry-run" in sys.argv
    out = {}

    s = io.open(RECAP, encoding="utf-8").read()
    for old, new in RECAP_EDITS:
        s = replace_kw_run(s, old, new, "07-recap")
    out[RECAP] = s
    print("  ✓ 07-recap.html — 5곳")

    s = io.open(SCRIPT, encoding="utf-8").read()
    out[SCRIPT] = patch_script(s)
    print("  ✓ SCRIPT.md — Line 3 재작성 · Line 4 3곳 · Line 7 1곳")

    if dry:
        print("\n--dry-run — 쓰지 않았다.")
        return 0
    for p, body in out.items():
        io.open(p, "w", encoding="utf-8", newline="\n").write(body)
    print("\n2개 파일을 고쳤다. 낭독을 다시 재고 모션을 다시 맞춰야 한다.")
