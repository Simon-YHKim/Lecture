def patch_script(s):
    i = s.find(LINE3_OLD_START)
    j = s.find(LINE3_OLD_END)
    if i < 0 or j < 0 or j < i:
        raise SystemExit("SCRIPT.md: Line 3 구간을 못 찾았다")
    s = s[:i] + LINE3_NEW + s[j:]
    for old, new in LINE4_EDITS + LINE7_EDITS:
        if old not in s:
            raise SystemExit(f"SCRIPT.md: 「{old[:48]}…」 를 못 찾았다")
        s = s.replace(old, new, 1)
    # 머리말의 보이스 디렉션도 좌표를 전제하고 있었다.
    s = s.replace(
        "**Voice direction:** 좌표를 말할 때는 숫자 앞에서 한 박자 쉰다.",
        "**Voice direction:** 치수를 말할 때는 숫자 앞에서 한 박자 쉰다.")
